void Set(int id) { g_lang = id >= 0 && id < Count ? id : En; }
int Get() { return g_lang; }

int FromCode(const char* code)
{
    for (int i = 0; i < Count; i++)
        if (code && strcmp(code, kLangs[i].code) == 0) return i;
    return -1;
}

int FromSystem()
{
    switch (PRIMARYLANGID(GetUserDefaultUILanguage())) {
    case LANG_CHINESE: return Zh;
    case LANG_JAPANESE: return Ja;
    case LANG_KOREAN: return Ko;
    case LANG_RUSSIAN: return Ru;
    case LANG_GERMAN: return De;
    case LANG_FRENCH: return Fr;
    case LANG_SPANISH: return Es;
    case LANG_PORTUGUESE: return Pt;
    default: return En;
    }
}

const char* T(const char* en)
{
    int l = g_lang;
    if (l == En || !en) return en;
    const char* const* row = Row(en);
    return row && row[l] && *row[l] ? row[l] : en;
}

