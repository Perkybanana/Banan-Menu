const char* const* Row(std::string_view en)
{
    static const auto index = [] {
        std::unordered_map<std::string_view, const char* const*> m;
        for (const auto& row : kTable) m.emplace(row[0], row);
        return m;
    }();
    auto it = index.find(en);
    return it == index.end() ? nullptr : it->second;
}

